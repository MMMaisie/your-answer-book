"""Constrained research pipeline. Valid structure is not validated divination."""
import json,re
from reading_knowledge import chart_facts,reference_label,validate_reading
VERSION='v5-constrained-analysis'
BRANCH_EN=dict(zip('子丑寅卯辰巳午未申酉戌亥',('Zi','Chou','Yin','Mao','Chen','Si','Wu','Wei','Shen','You','Xu','Hai')))
KIN_EN={'父母':'Parents','兄弟':'Siblings','妻财':'Wealth','官鬼':'Office','子孙':'Offspring'}
REL_ZH={'生':'生','克':'克','比和':'同五行','被生（对方生本方）':'受生于','被克（对方克本方）':'受克于'}
REL_EN={'生':'generates','克':'controls','比和':'shares an element with','被生（对方生本方）':'is generated by','被克（对方克本方）':'is controlled by'}
class PlanError(ValueError):pass

def question_kind(question):
 question=question.casefold()
 # Only explicit supported intents. No guessing gender, relationship or medical intent.
 if any(x in question for x in ('求财','收入','生意','profit','income')):return 'wealth','妻财'
 if any(x in question for x in ('升迁','升职','promotion')):return 'promotion','官鬼'
 if any(x in question for x in ('子久出','孩子','子女','son','daughter','child')):return 'child','子孙'
 raise PlanError('占问对象未在当前支持范围内；需明确对象，不能自动猜用神')

def prepare(question,cast,rules):
 kind,kin=question_kind(question)
 candidates=[r['position'] for r in cast['rows'] if r['kin']==kin]
 if not candidates:raise PlanError('用神未现：需单独核对伏神取用，当前流程不自动下结论')
 facts=chart_facts(cast);catalog=[]
 def add(fid,zh,en):catalog.append({'id':fid,'zh':zh,'en':en})
 for row in facts['lines']:
  pos=row['position'];b=row['branch'];eb=BRANCH_EN[b];prefix=f'第{pos}爻{b}';ep=f'Line {pos} ({eb})'
  add(f'{pos}.identity',prefix+row['kin']+'。',ep+' is '+KIN_EN[row['kin']]+'.')
  if row['void']:add(f'{pos}.void',prefix+'旬空。',ep+' is void.')
  if row['month_break']:add(f'{pos}.break',prefix+'月破。',ep+' is month-broken.')
  for period,label in (('month','月建'),('day','日辰')):
   rel=row.get(period)
   if rel:
    src=rel['source'];target=rel['target'];code=rel['element_relation']
    add(f'{pos}.{period}',label+src+REL_ZH[code]+target+'。',period.title()+' '+BRANCH_EN[src]+' '+REL_EN[code]+' '+BRANCH_EN[target]+'.')
  changed=row.get('changed')
  if changed:
   src=changed['source'];target=changed['target'];code=changed['element_relation']
   add(f'{pos}.changed',f'第{pos}爻变支{src}'+REL_ZH[code]+target+'。',f'Changed {BRANCH_EN[src]} at line {pos} '+REL_EN[code]+' original '+BRANCH_EN[target]+'.')
   if changed['advance']:add(f'{pos}.advance',f'第{pos}爻{target}化{src}为进神。',f'Line {pos} advances from {BRANCH_EN[target]} to {BRANCH_EN[src]}.')
   if changed['retreat']:add(f'{pos}.retreat',f'第{pos}爻{target}化{src}为退神。',f'Line {pos} retreats from {BRANCH_EN[target]} to {BRANCH_EN[src]}.')
 return {'version':VERSION,'question':question,'kind':kind,'focal_kin':kin,'candidate_positions':candidates,'facts':catalog,'rules':rules,'limits':'结构事实不等于有效生克、主次、吉凶或应期；本版本不生成确定成败和日期。'}

def validate_plan(plan,payload):
 if not isinstance(plan,dict) or set(plan)!={'kind','candidate_positions','primary_position','fact_ids','rule_ids'}:raise PlanError('分析字段缺失或出现未授权自由文本')
 if plan['kind']!=payload['kind']:raise PlanError('占问类别与明确问题不符')
 if plan['candidate_positions']!=payload['candidate_positions']:raise PlanError('漏掉或编造候选用神')
 primary=plan['primary_position']
 if primary is not None:raise PlanError('当前多现主次未独立验证，必须保留primary_position=null')
 for key,allowed in [('fact_ids',{r['id'] for r in payload['facts']}),('rule_ids',{r['id'] for r in payload['rules']})]:
  values=plan[key]
  if not isinstance(values,list) or not values or any(not isinstance(x,str) or x not in allowed for x in values) or len(values)!=len(set(values)):raise PlanError('无效或重复的依据ID')
 if len(plan['rule_ids'])<2:raise PlanError('至少两条可核对来源')
 required={f'{p}.identity' for p in payload['candidate_positions']}
 required|={f['id'] for f in payload['facts'] if f['id'].endswith(('.void','.break','.advance','.retreat'))}
 if not required.issubset(plan['fact_ids']):raise PlanError('分析遗漏用神或关键空破进退事实')
 return plan

def size(text,lang):return len(text) if lang=='zh' else len(text.split())

def bounded_text(base,extras,low,high,lang):
 text=base
 for sentence in extras:
  candidate=text+('' if lang=='zh' else ' ')+sentence
  if size(candidate,lang)<=high:text=candidate
  if size(text,lang)>=low:break
 if not low<=size(text,lang)<=high:raise PlanError('完整句子无法满足字数范围；不截断、不补空字')
 return text

def render(plan,payload,lang):
 validate_plan(plan,payload)
 if lang not in ('zh','en'):raise PlanError('语言无效')
 selected=[f for f in payload['facts'] if f['id'] in plan['fact_ids']]
 selected.sort(key=lambda f:(not f['id'].endswith(('.void','.break','.advance','.retreat','.changed')),int(f['id'].split('.')[0]) not in payload['candidate_positions']))
 chosen=[f[lang] for f in selected]
 positions=payload['candidate_positions'];kin=payload['focal_kin']
 rules=[r for r in payload['rules'] if r['id'] in plan['rule_ids']]
 # Same plan, factual catalog and priorities for both languages. No second AI interpretation.
 if lang=='zh':
  intro='当前需先核对条件，不能据此确定成败或日期。'
  lead='按明确占问以'+kin+'为参照，候选为第'+'、'.join(map(str,positions))+'爻。'
  free_body=bounded_text(intro+lead,chosen,60,80,lang)
  free='【初判】'+intro+'\n【关键依据】'+free_body[len(intro):]
  a=lead+'用神多现须比较问意、世应、日月与空破；本次保留候选，不擅自指定主爻。'
  b='以下仅为可复核的结构事实，不能把旬空视为永远无用，也不能把月破直接等同失败。'
  c='行动前应核实对应的现实条件。出旬、填实和出月是不同观察条件，不能混成同一日期。没有独立核验的应期，本次不提供具体日期；出现相反条件时应重新检查，而非只保留有利信号。'
  additions=chosen+['动静与结构生克必须结合日月扶助分析，不能只见某一关系便判成败。','化进化退表示变化方向，其意义取决于所问对象，不能直接写成有归意或必然推进。','主次未确认前，各候选的有利和受限条件都应保留。']
  total=bounded_text(a+b+c,additions,250,300,lang);b+=total[len(a+b+c):]
  paid='【盘面与主次】'+a+'\n【阻力与可变条件】'+b+'\n【行动与边界】'+c+'\n【规则依据】'+'；'.join(dict.fromkeys(reference_label(r,lang) for r in rules))
 else:
  intro='Conditions need review; this does not establish success or specific timing.'
  lead=KIN_EN[kin]+' is the reference for the stated question. Candidate lines: '+', '.join(map(str,positions))+'.'
  free_body=bounded_text(intro+' '+lead,['A firm direction remains unresolved until their limiting and supportive conditions are compared.'],35,60,lang)
  free='【Initial reading】'+intro+'\n【Key evidence】'+free_body[len(intro):].strip()
  a='The explicit question is assessed through '+KIN_EN[kin]+', with candidates at positions '+', '.join(map(str,positions))+'. Multiple candidates require comparison of the question, self and response, calendar support and limitations. No primary line has been independently established.'
  b='The listed relationships are structural facts. Void does not mean permanent uselessness, and a month break does not establish failure. '
  c='Check the relevant real conditions before acting. Leaving a void period, filling a line and leaving a month are distinct conditions, not a single date. No specific timing is supplied without independent verification. Keep opposing evidence visible and reassess if conditions change. Advancing or retreating describes a transformation, not a guaranteed outcome or an intention to return.'
  total=bounded_text(a+' '+b+' '+c,chosen+['Each candidate must be assessed against calendar support rather than selecting whichever looks strongest.','Effective generation or control still requires review of strength and other conditions.'],150,210,lang)
  b+=total[len(a+' '+b+' '+c):]
  paid='【Chart and priorities】'+a+'\n【Obstacles and conditions】'+b+'\n【Actions and boundaries】'+c+'\n【Source notes】'+'; '.join(dict.fromkeys(reference_label(r,lang) for r in rules))
 validate_reading(free,lang,'free');validate_reading(paid,lang,'paid',free,rules)
 return {'free':free,'paid':paid,'status':'STRUCTURE_CHECKED_SEMANTIC_REVIEW_REQUIRED','plan_version':VERSION}
